package ssac.util.swing.plot;

/**
 * プロット時の点描画スタイル。
 * 
 * @version 2.1.0	2013/07/10
 * @since 2.1.0
 */
public enum PlotMarkStyles
{
	//------------------------------------------------------------
	// Constnts
	//------------------------------------------------------------

	/** 点を描画しない **/
	NONE(0),
	/** 四角点 **/
	POINTS(1),
	/** 円点 **/
	DOTS(2),
	/** データ系列ごとに異なる記号 **/
	VARIOUS(3),
	/** 大きな円点 **/
	BIGDOTS(4),
	/** ドット(1 pixel) **/
	PIXELS(5);

	//------------------------------------------------------------
	// Fields
	//-----------------------------------------------------------
	
	private int	_id;

	//------------------------------------------------------------
	// Constructions
	//------------------------------------------------------------
	
	private PlotMarkStyles(int id) {
		_id = id;
	}

	//------------------------------------------------------------
	// Public interfaces
	//------------------------------------------------------------
	
	public final int id() {
		return _id;
	}

	//------------------------------------------------------------
	// Internal methods
	//------------------------------------------------------------
}
